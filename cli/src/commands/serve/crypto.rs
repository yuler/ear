use std::fs::File;
use std::io::{self, Read};
use std::path::Path;

/// Fill `buf` with bytes from the operating system's CSPRNG.
/// Fails closed if the OS entropy source is unavailable — never falls back to weak hashes.
pub fn fill_os_random(buf: &mut [u8]) -> Result<(), String> {
    getrandom::getrandom(buf).map_err(|e| format!("OS CSPRNG unavailable: {e}"))
}

/// Generate a lowercase hex string from `bytes` OS-random bytes.
pub fn generate_hex_secret(bytes: usize) -> Result<String, String> {
    generate_hex_secret_with(bytes, fill_os_random)
}

pub fn generate_hex_secret_with<F>(bytes: usize, mut rng: F) -> Result<String, String>
where
    F: FnMut(&mut [u8]) -> Result<(), String>,
{
    let mut raw = vec![0u8; bytes];
    rng(&mut raw)?;
    let mut out = String::with_capacity(bytes * 2);
    for b in raw {
        out.push_str(&format!("{b:02x}"));
    }
    Ok(out)
}

/// Generate an unbiased 4-digit pairing code in `1000..=9999` using OS CSPRNG rejection sampling.
pub fn generate_pair_code() -> Result<String, String> {
    generate_pair_code_with(fill_os_random)
}

pub fn generate_pair_code_with<F>(mut rng: F) -> Result<String, String>
where
    F: FnMut(&mut [u8]) -> Result<(), String>,
{
    const RANGE: u32 = 9000;
    const LIMIT: u32 = (u32::MAX / RANGE) * RANGE;
    let mut buf = [0u8; 4];
    loop {
        rng(&mut buf)?;
        let v = u32::from_be_bytes(buf);
        if v < LIMIT {
            let n = 1000 + (v % RANGE);
            return Ok(format!("{n:04}"));
        }
    }
}

/// Constant-time byte slice equality for pairing codes and bearer tokens.
pub fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (&x, &y) in a.iter().zip(b.iter()) {
        diff |= std::hint::black_box(x ^ y);
    }
    std::hint::black_box(diff) == 0
}

